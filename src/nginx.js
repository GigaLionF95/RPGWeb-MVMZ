// nginx config for file offload: rpgm-web answers game file requests with
// X-Accel-Redirect and nginx sends the bytes (sendfile, no Node in the path).
import { GAME_SANDBOX } from './server/index.js';

/** Headers rpgm-web would have sent; nginx drops them on an X-Accel-Redirect. */
function fileHeaders(config) {
  const csp = [];
  if (config.gameSandbox !== false) csp.push(`sandbox ${GAME_SANDBOX}`);
  if (config.frameAncestors && config.frameAncestors !== '*') csp.push(`frame-ancestors 'self' ${config.frameAncestors}`);
  return [
    ...(csp.length ? [`add_header Content-Security-Policy "${csp.join('; ')}" always;`] : []),
    'add_header Access-Control-Allow-Origin "*" always;',
    'add_header X-Content-Type-Options nosniff always;',
    'add_header Vary Accept-Encoding always;',
  ];
}

export function nginxSnippet(config, { root }) {
  const dir = root.replace(/\/+$/, '') + '/';
  const common = (extra = []) => [
    'internal;',
    `alias ${dir};`,
    'sendfile on; tcp_nopush on; gzip off;',
    ...fileHeaders(config),
    ...extra,
  ].map((l) => `    ${l}`).join('\n');
  return `# rpgm-web: nginx sends game files itself (X-Accel-Redirect).
# Generated by "rpgm-web nginx-snippet" — run it again after changing
# RPGM_FRAME_ANCESTORS or RPGM_GAME_SANDBOX, or the data folder.
#
# 1. Put these locations into the server { } block that proxies to rpgm-web.
# 2. In the location that proxies to rpgm-web, add:
#        proxy_set_header X-Rpgm-Accel 1;
# 3. nginx must be able to read ${dir}
#    (with Docker: bind-mount the data folder, see the README).

location /__rpgm_files/ {
${common()}
}
location /__rpgm_files_br/ {
${common(['add_header Content-Encoding br always;'])}
}
location /__rpgm_files_gz/ {
${common(['add_header Content-Encoding gzip always;'])}
}
# Games kept on another server of the pool (RPGM_REPLICAS): nginx fetches
# them from that server directly. Use IP addresses in RPGM_ADVERTISE_URL,
# or add a "resolver" line for host names.
location ~ ^/__rpgm_node/(?<rpgm_node>[A-Za-z0-9.:_\\[\\]-]+)$ {
    internal;
    proxy_pass http://$rpgm_node$request_uri;
    proxy_http_version 1.1;
    proxy_set_header Connection "";
    proxy_set_header Host $host;
    proxy_set_header X-Rpgm-Forwarded 1;
    proxy_set_header X-Rpgm-Accel "";
    proxy_buffering off;
}
`;
}
